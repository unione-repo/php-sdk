     *
     * @var string|null
     */
    private $status;

    /**
     * Debug message.
     * Example: `Record updated`.
     *
     * @var string|null
     */
    private $message;

    /**
     * @param array<string, mixed> $data Decoded JSON.
     */
    public static function fromArray(array $data): self
    {
        $model = new self();
        $model->status = Data::string($data['status'] ?? null);
        $model->message = Data::string($data['message'] ?? null);

        return $model;
    }

    /**
     * "success" string
     */
